def mmss(t):
    s = int(t)
    return f"{s // 60:02d}:{s % 60:02d}"


def transcript_lines(conversation, changed=None):
    """Строки транскрипта; реплика changed помечается ИЗМЕНЕНО (переигровка)."""
    lines = []
    for u in conversation["transcript"]:
        when = mmss(u["t"]) if u.get("t") is not None else (u.get("timestamp") or "—")
        mark = " | ИЗМЕНЕНО" if u["id"] == changed else ""
        lines.append(f"[{u['id']} | {when}{mark}] {u['speaker']}: {u['text']}")
    return lines


PAUSE = 60  # секунд: ответ оператора позже этого после реплики клиента считается паузой


def facts_block(conversation):
    """Общие факты, найденные кодом без привязки к критериям и языку. Модель обязана проверять их по репликам."""
    ts = conversation["transcript"]
    ops = [u for u in ts if u["speaker"] == "operator"]
    clients = [u for u in ts if u["speaker"] == "client"]
    bots = [u for u in ts if u["speaker"] == "bot"]
    when = lambda u: mmss(u["t"]) if u.get("t") is not None else (u.get("timestamp") or "—")
    lines = ["Факты из транскрипта (найдены автоматически, проверяй по репликам):"]
    if ops:
        first = ops[0]
        lines.append(f"- Первая реплика оператора: {first['id']} ({when(first)}). Все реплики до неё — бота, клиента или системы.")
    else:
        lines.append("- Реплик оператора нет.")
    lines.append(f"- Реплик бота: {len(bots)}." if bots else "- Реплик бота нет.")
    events = [f"[{u['id']}] {u['text']}" for u in ts if u["speaker"] == "system"]
    lines.append("- Системные события: " + ("; ".join(events) if events else "нет") + ".")
    lines.append(f"- Последним говорил: {ts[-1]['speaker']} ({ts[-1]['id']})." + (f" Последняя реплика оператора: {ops[-1]['id']}." if ops else ""))
    pauses, last_client = [], None
    for u in ts:
        if u["speaker"] == "client":
            last_client = u
        elif u["speaker"] == "operator":
            if last_client and u is not ops[0] and u.get("t") is not None and last_client.get("t") is not None and u["t"] - last_client["t"] > PAUSE:
                pauses.append(f"{last_client['id']} → {u['id']}: {mmss(u['t'] - last_client['t'])}")
            last_client = None
        elif u["speaker"] == "bot":
            last_client = None
    lines.append("- Паузы оператора дольше 60 с (первая реакция не считается): " + (", ".join(pauses) if pauses else "нет") + ".")
    lines.append(f"- Реплик оператора: {len(ops)}, клиента: {len(clients)}.")
    return "\n".join(lines)


def build_user(conversation, checklist, changed=None):
    lines = [f"Канал: {conversation['channel']}. Язык: {conversation['language']}.", "", "Критерии:"]
    for c in checklist["criteria"]:
        kind = "yes/no" if c["type"] == "yes_no" else "шкала"
        lines.append(f"\n{c['id']} | {c.get('section') or ''} | {c['title']} | {kind}")
        if c.get("is_critical"):
            lines.append("Грубое нарушение: yes — нарушение есть, no — нет. NA запрещён.")
        lines.append(f"Инструкция: {c['instruction']}")
        if c["type"] == "scale":
            lines.append("Ступени: " + "; ".join(f"{s['value']} — {s.get('label', '')}" for s in c["steps"]))
        if c.get("na_allowed") and not c.get("is_critical"):
            lines.append(f"NA разрешён, если: {c['na_condition']}")
        else:
            lines.append("NA запрещён.")
    if config.PROMPT_FACTS:
        lines += ["", facts_block(conversation)]
    lines += ["", "Транскрипт:"] + transcript_lines(conversation, changed)
    return "\n".join(lines)
